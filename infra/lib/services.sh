#!/usr/bin/env bash
# Services and operating-system hardening: MariaDB, ClamAV, fail2ban, unattended-upgrades,
# auditd, sysctl, journald, swap, time sync, and the systemd units.
# Sourced by bootstrap.sh. Needs lib/common.sh, lib/users.sh and a loaded configuration.
# shellcheck shell=bash

# --- MariaDB -----------------------------------------------------------------------
svc_mariadb_ping() { mariadb-admin ping >/dev/null 2>&1; }

# Inside the test container there is no systemd, so the server is started by hand and left
# running for the verifier.
svc_mariadb_start_container() {
  svc_mariadb_ping && return 0
  install -d -m 0755 -o mysql -g mysql /run/mysqld
  setsid nohup mariadbd --user=mysql >/var/log/oc-test-mariadbd.log 2>&1 &
  for _ in $(seq 1 90); do
    svc_mariadb_ping && return 0
    sleep 1
  done
  oc_die "MariaDB did not start (see /var/log/oc-test-mariadbd.log)"
}

svc_mariadb() {
  local before=$OC_CHANGES
  oc_install_stdin /etc/mysql/mariadb.conf.d/99-oc.cnf 0644 root root <<'EOF'
# Managed by infra/bootstrap.sh
[mariadbd]
# Local only. The app containers reach MariaDB through its unix socket (a mounted folder);
# nothing outside the server can reach it.
bind-address            = 127.0.0.1
skip-name-resolve
character-set-server    = utf8mb4
collation-server        = utf8mb4_unicode_ci
local-infile            = 0
skip-symbolic-links
max_connections         = 100
# Memory budget (spec section 5): about 1 GB for MariaDB. The baseline phase measures it.
innodb_buffer_pool_size = 512M
EOF
  if oc_container_mode; then
    if [[ $OC_CHANGES -ne $before ]] && svc_mariadb_ping; then
      mariadb-admin shutdown >/dev/null 2>&1 || true
      for _ in $(seq 1 30); do
        svc_mariadb_ping || break
        sleep 1
      done
    fi
    svc_mariadb_start_container
  else
    systemctl enable mariadb >/dev/null 2>&1
    if [[ $OC_CHANGES -ne $before ]] || ! systemctl is-active --quiet mariadb; then
      systemctl restart mariadb
    fi
    for _ in $(seq 1 60); do
      svc_mariadb_ping && break
      sleep 1
    done
    svc_mariadb_ping || oc_die "MariaDB is not answering"
  fi
}

# svc_databases: one database and one user per environment, the user limited to its own
# database. The password comes from the environment file, so the file and the server
# always agree. It reaches MariaDB on standard input only, never in an argument list.
svc_databases() {
  local env pass exists host
  local -a anon=()
  mariadb -N -B <<'EOF' >/dev/null || oc_die "MariaDB root access over the socket failed"
SELECT 1;
EOF
  # No anonymous accounts, no sample database.
  mapfile -t anon < <(mariadb -N -B -e "SELECT Host FROM mysql.global_priv WHERE User = ''")
  for host in "${anon[@]}"; do
    [[ -n $host ]] || continue
    mariadb -e "DROP USER ''@'$host'"
    oc_changed "removed an anonymous MariaDB account"
  done
  mariadb -e "DROP DATABASE IF EXISTS test"
  for env in "${OC_ENV_LIST[@]}"; do
    pass=$(users_env_value "$env" DATABASE_PASSWORD)
    [[ $pass =~ ^[A-Za-z0-9]{24,}$ ]] || oc_die "DATABASE_PASSWORD in $OC_SECRET_DIR/$env.env is missing or has unexpected characters"
    exists=$(mariadb -N -B -e "SELECT COUNT(*) FROM information_schema.SCHEMATA WHERE SCHEMA_NAME = 'oc_$env'")
    mariadb <<EOF
CREATE DATABASE IF NOT EXISTS \`oc_$env\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS 'oc_$env'@'localhost' IDENTIFIED BY '$pass';
ALTER USER 'oc_$env'@'localhost' IDENTIFIED BY '$pass' WITH MAX_USER_CONNECTIONS 40;
REVOKE ALL PRIVILEGES, GRANT OPTION FROM 'oc_$env'@'localhost';
GRANT ALL PRIVILEGES ON \`oc_$env\`.* TO 'oc_$env'@'localhost';
EOF
    if [[ $exists == 0 ]]; then
      oc_changed "created database oc_$env and its user"
    fi
  done
  mariadb -e "FLUSH PRIVILEGES"
}

# --- ClamAV ------------------------------------------------------------------------
# The Debian clamd.conf is generated by the package. The settings we need are kept in one
# marked block at the end, and any earlier copy of the same setting is dropped, so a rerun
# produces the same file.
SVC_CLAMD_BEGIN='# --- managed by infra/bootstrap.sh (begin) ---'
SVC_CLAMD_END='# --- managed by infra/bootstrap.sh (end) ---'

svc_clamd_render() {
  local file=/etc/clamav/clamd.conf line key skip=0
  while IFS= read -r line || [[ -n $line ]]; do
    if [[ $line == "$SVC_CLAMD_BEGIN" ]]; then
      skip=1
      continue
    fi
    if [[ $line == "$SVC_CLAMD_END" ]]; then
      skip=0
      continue
    fi
    ((skip)) && continue
    key=${line%%[[:space:]]*}
    case $key in
      LocalSocket | LocalSocketGroup | LocalSocketMode | TCPSocket | TCPAddr | StreamMaxLength | MaxFileSize | MaxScanSize) continue ;;
      *) ;;
    esac
    printf '%s\n' "$line"
  done <"$file"
  cat <<EOF
$SVC_CLAMD_BEGIN
# Scan requests come over this socket only. There is no TCPSocket or TCPAddr: clamd must
# never listen on the network. The group is the one the environment users belong to.
LocalSocket $OC_CLAMD_SOCKET
LocalSocketGroup $OC_CLAMD_GROUP
LocalSocketMode 660
# Uploads are limited to 25 MB by default (spec section 10.4); these leave room above that.
StreamMaxLength 50M
MaxFileSize 50M
MaxScanSize 200M
$SVC_CLAMD_END
EOF
}

svc_clamav() {
  local before=$OC_CHANGES conf
  [[ -f /etc/clamav/clamd.conf ]] || oc_die "clamav-daemon is not installed"
  oc_mktemp_into conf
  svc_clamd_render >"$conf"
  oc_install_tmp "$conf" /etc/clamav/clamd.conf 0644 root root
  # The package starts clamd through a systemd socket unit. Its group and mode are set here;
  # the unit's own default is a world-accessible socket.
  oc_ensure_dir /etc/systemd/system/clamav-daemon.socket.d 0755 root root
  oc_install_stdin /etc/systemd/system/clamav-daemon.socket.d/oc.conf 0644 root root <<EOF
# Managed by infra/bootstrap.sh
[Socket]
SocketGroup=$OC_CLAMD_GROUP
SocketMode=0660
EOF
  if oc_container_mode; then
    oc_log "container: ClamAV configured, not started (it needs its signature download)"
    return 0
  fi
  systemctl daemon-reload
  # clamd will not start without signatures. Fetch them now rather than waiting for the timer.
  if ! compgen -G '/var/lib/clamav/main.c[lv]d' >/dev/null && ! compgen -G '/var/lib/clamav/main.inc' >/dev/null; then
    oc_log "downloading the first ClamAV signatures (a few minutes)"
    systemctl stop clamav-freshclam >/dev/null 2>&1 || true
    freshclam --quiet || oc_die "freshclam could not download the signatures. Rerun the bootstrap in a few minutes (ClamAV's mirrors rate-limit repeat downloads)."
    oc_changed "downloaded ClamAV signatures"
  fi
  systemctl enable clamav-freshclam >/dev/null 2>&1
  systemctl start clamav-freshclam
  systemctl enable clamav-daemon.socket clamav-daemon.service >/dev/null 2>&1
  if [[ $OC_CHANGES -ne $before ]]; then
    systemctl restart clamav-daemon.socket clamav-daemon.service
  else
    systemctl start clamav-daemon.socket clamav-daemon.service
  fi
}

# --- fail2ban ----------------------------------------------------------------------
svc_fail2ban() {
  local before=$OC_CHANGES
  oc_install_stdin /etc/fail2ban/jail.d/oc-sshd.local 0644 root root <<EOF
# Managed by infra/bootstrap.sh
[DEFAULT]
backend = systemd
bantime = 1h
bantime.increment = true
bantime.maxtime = 1w
findtime = 10m

[sshd]
enabled = true
port = $OC_SSH_PORT
maxretry = 4
EOF
  oc_quiet fail2ban-client -t || oc_die "fail2ban rejects its configuration"
  if oc_container_mode; then
    return 0
  fi
  systemctl enable fail2ban >/dev/null 2>&1
  if [[ $OC_CHANGES -ne $before ]] || ! systemctl is-active --quiet fail2ban; then
    systemctl restart fail2ban
  fi
}

# --- unattended upgrades ------------------------------------------------------------
svc_unattended_upgrades() {
  oc_install_stdin /etc/apt/apt.conf.d/20auto-upgrades 0644 root root <<'EOF'
// Managed by infra/bootstrap.sh
APT::Periodic::Update-Package-Lists "1";
APT::Periodic::Unattended-Upgrade "1";
APT::Periodic::AutocleanInterval "7";
EOF
  # Security updates only (Ubuntu's default origins). No automatic reboot: the window is an
  # open item (O11). Node and MariaDB come from their own repositories and are updated by
  # a person, on purpose.
  oc_install_stdin /etc/apt/apt.conf.d/52oc-unattended-upgrades 0644 root root <<'EOF'
// Managed by infra/bootstrap.sh
Unattended-Upgrade::Automatic-Reboot "false";
Unattended-Upgrade::Remove-Unused-Dependencies "true";
EOF
  if ! oc_container_mode; then
    systemctl enable apt-daily.timer apt-daily-upgrade.timer unattended-upgrades >/dev/null 2>&1
    systemctl start apt-daily.timer apt-daily-upgrade.timer
  fi
}

# --- auditd ------------------------------------------------------------------------
svc_auditd() {
  local before=$OC_CHANGES
  oc_install_stdin /etc/audit/rules.d/oc.rules 0640 root root <<'EOF'
## Managed by infra/bootstrap.sh
## The secret files and the setup itself
-w /etc/oc -p wa -k oc_secrets
-w /etc/ssl/oc -p wa -k oc_tls
-w /etc/nginx -p wa -k oc_nginx
-w /etc/ufw -p wa -k oc_firewall
-w /etc/systemd/system -p wa -k oc_units
-w /etc/ssh/sshd_config -p wa -k oc_sshd
-w /etc/ssh/sshd_config.d -p wa -k oc_sshd
## sudo
-w /etc/sudoers -p wa -k oc_sudo
-w /etc/sudoers.d -p wa -k oc_sudo
-w /var/log/sudo.log -p wa -k oc_sudo
-w /usr/bin/sudo -p x -k oc_sudo
## logins
-w /var/log/lastlog -p wa -k oc_logins
-w /var/log/wtmp -p wa -k oc_logins
-w /var/log/btmp -p wa -k oc_logins
-w /run/utmp -p wa -k oc_logins
## accounts
-w /etc/passwd -p wa -k oc_identity
-w /etc/shadow -p wa -k oc_identity
-w /etc/group -p wa -k oc_identity
-w /etc/gshadow -p wa -k oc_identity
EOF
  if oc_container_mode; then
    return 0
  fi
  systemctl enable auditd >/dev/null 2>&1
  systemctl start auditd
  if [[ $OC_CHANGES -ne $before ]]; then
    augenrules --load >/dev/null
  fi
}

# --- kernel and network hardening --------------------------------------------------
svc_sysctl() {
  local before=$OC_CHANGES
  oc_install_stdin /etc/sysctl.d/99-oc-hardening.conf 0644 root root <<'EOF'
# Managed by infra/bootstrap.sh
# Network: no redirects or source routing, reverse-path filtering, SYN cookies.
net.ipv4.conf.all.rp_filter = 1
net.ipv4.conf.default.rp_filter = 1
net.ipv4.conf.all.accept_redirects = 0
net.ipv4.conf.default.accept_redirects = 0
net.ipv4.conf.all.secure_redirects = 0
net.ipv4.conf.default.secure_redirects = 0
net.ipv6.conf.all.accept_redirects = 0
net.ipv6.conf.default.accept_redirects = 0
net.ipv4.conf.all.send_redirects = 0
net.ipv4.conf.default.send_redirects = 0
net.ipv4.conf.all.accept_source_route = 0
net.ipv4.conf.default.accept_source_route = 0
net.ipv6.conf.all.accept_source_route = 0
net.ipv4.conf.all.log_martians = 1
net.ipv4.icmp_echo_ignore_broadcasts = 1
net.ipv4.icmp_ignore_bogus_error_responses = 1
net.ipv4.tcp_syncookies = 1
net.ipv4.tcp_rfc1337 = 1
# Kernel
kernel.randomize_va_space = 2
kernel.kptr_restrict = 2
kernel.dmesg_restrict = 1
kernel.sysrq = 0
kernel.unprivileged_bpf_disabled = 1
net.core.bpf_jit_harden = 2
fs.suid_dumpable = 0
fs.protected_hardlinks = 1
fs.protected_symlinks = 1
fs.protected_fifos = 2
fs.protected_regular = 2
# Use the swap file only under real memory pressure.
vm.swappiness = 10
EOF
  if oc_container_mode || [[ $OC_CHANGES -eq $before ]]; then
    return 0
  fi
  # -e: skip a setting this kernel does not have instead of failing the whole file.
  sysctl -e -q --system >/dev/null
}

# --- journald, swap, time ----------------------------------------------------------
svc_journald() {
  local before=$OC_CHANGES
  oc_ensure_dir /etc/systemd/journald.conf.d 0755 root root
  oc_install_stdin /etc/systemd/journald.conf.d/oc.conf 0644 root root <<'EOF'
# Managed by infra/bootstrap.sh
[Journal]
Storage=persistent
Compress=yes
SystemMaxUse=1G
SystemKeepFree=2G
MaxRetentionSec=3month
EOF
  if ! oc_container_mode; then
    oc_ensure_dir /var/log/journal 2755 root systemd-journal
    if [[ $OC_CHANGES -ne $before ]]; then
      systemctl restart systemd-journald
    fi
  fi
}

svc_swap() {
  if oc_container_mode; then
    oc_log "container: swap skipped"
    return 0
  fi
  if [[ -n $(swapon --show --noheadings) ]]; then
    oc_log "swap already active"
    return 0
  fi
  if [[ ! -e /swapfile ]]; then
    # Created private from the start: swap holds pieces of memory.
    (
      umask 077
      fallocate -l "$OC_SWAP_SIZE" /swapfile
    )
    chmod 0600 /swapfile
    mkswap /swapfile >/dev/null
    oc_changed "created /swapfile ($OC_SWAP_SIZE)"
  fi
  swapon /swapfile
  if ! grep -qE '^/swapfile[[:space:]]' /etc/fstab; then
    printf '%s\n' '/swapfile none swap sw 0 0' >>/etc/fstab
    oc_changed "added /swapfile to /etc/fstab"
  fi
}

svc_time() {
  local current
  if oc_container_mode; then
    [[ -f /usr/share/zoneinfo/$OC_TIMEZONE ]] || oc_die "unknown time zone $OC_TIMEZONE"
    return 0
  fi
  [[ -f /usr/share/zoneinfo/$OC_TIMEZONE ]] || oc_die "unknown time zone $OC_TIMEZONE"
  current=$(timedatectl show -p Timezone --value)
  if [[ $current != "$OC_TIMEZONE" ]]; then
    timedatectl set-timezone "$OC_TIMEZONE"
    oc_changed "time zone set to $OC_TIMEZONE"
  fi
  systemctl enable systemd-timesyncd >/dev/null 2>&1
  systemctl start systemd-timesyncd
  timedatectl set-ntp true
}

# --- the Cloudflare refresh (a root systemd service and timer) -----------------------
svc_install_units() {
  local unit
  for unit in oc-cloudflare-ips.service oc-cloudflare-ips.timer; do
    oc_install_file "$OC_INFRA_DIR/systemd/$unit" "$OC_UNIT_DIR/$unit" 0644 root root
  done
  # The weekly refresh runs from a copy of the libraries, so it does not need this checkout.
  oc_ensure_dir "$OC_RUNTIME_LIB_DIR" 0755 root root
  for unit in common.sh firewall.sh nginx.sh; do
    oc_install_file "$OC_INFRA_DIR/lib/$unit" "$OC_RUNTIME_LIB_DIR/$unit" 0644 root root
  done
  oc_install_file "$OC_INFRA_DIR/bin/oc-cloudflare-ips" "$OC_RUNTIME_BIN" 0755 root root
  if oc_container_mode; then
    return 0
  fi
  systemctl daemon-reload
  systemctl enable oc-cloudflare-ips.timer >/dev/null 2>&1
  systemctl start oc-cloudflare-ips.timer
}

# --- unused services ----------------------------------------------------------------
svc_disable_unused() {
  local u state
  if oc_container_mode; then
    return 0
  fi
  for u in "${OC_UNUSED_UNITS[@]}"; do
    state=$(systemctl is-enabled "$u" 2>/dev/null || true)
    # Empty: the unit does not exist here. Masked: already off for good.
    if [[ -z $state || $state == masked ]]; then
      continue
    fi
    systemctl mask --now "$u" >/dev/null 2>&1
    oc_changed "masked the unused service $u (was $state)"
  done
}

# --- Lynis ---------------------------------------------------------------------------
svc_lynis() {
  local idx
  if oc_container_mode || [[ ${OC_SKIP_LYNIS:-0} == 1 ]]; then
    oc_log "Lynis skipped"
    return 0
  fi
  oc_log "running Lynis (a minute or two)"
  lynis audit system --quick --no-colors --quiet >/dev/null 2>&1 || true
  idx=$(sed -n 's/^hardening_index=//p' /var/log/lynis-report.dat 2>/dev/null | head -n 1 || true)
  oc_log "Lynis hardening index: ${idx:-unknown} (report: /var/log/lynis-report.dat)"
  oc_next "Record the Lynis hardening index (${idx:-unknown}) in docs/phase0/report.md."
}
